/* ── Telegram: ссылка и первое сообщение ── */

/**
 * Ссылка в личку с готовым текстом: https://t.me/lstmind?text=...
 * Формат из документации Telegram (Public username links: t.me/<username>?text=<draft_text>):
 * текст встаёт в поле ввода, если человеку можно писать в этот чат. Тот же формат уже работал
 * в калькуляторе главной и на услугах. В веб-версии Telegram текст может не подставиться, ссылка при этом просто открывает чат.
 * Без текста: голая ссылка на чат.
 */
export const tgHref = (text?: string) => (text ? `${SITE.telegram}?text=${encodeURIComponent(text)}` : SITE.telegram);

const HI = "Здравствуйте!";
const ON = "на lstmind.ru";

/** откуда человек пишет: по этому собирается первое сообщение */
export type TgFrom =
  /** страница без своего текста: политика, согласие, 404 */
  | { kind: "site" }
  /** главная */
  | { kind: "home" }
  /** любая страница по имени: "Обо мне", "Сайты по нишам" */
  | { kind: "page"; name: string }
  /** страница услуги, name: h1 услуги */
  | { kind: "service"; name: string }
  /** страница ниши, name: h1 ниши */
  | { kind: "niche"; name: string }
  /** разбор работы, name: название проекта */
  | { kind: "case"; name: string }
  /** все работы, /works */
  | { kind: "works" }
  /** бесплатный аудит; diag: формулировка "диагностика" для /uslugi/pochinit-sayt */
  | { kind: "audit"; diag?: boolean };

/**
 * Готовое первое сообщение. Человеку не надо придумывать первую фразу, а я сразу вижу, откуда он.
 * Сообщения со "вставьте сюда" кончаются пробелом: курсор встаёт после двоеточия.
 */
export function tgText(from: TgFrom): string {
  switch (from.kind) {
    case "site":
      return `${HI} Пишу с сайта lstmind.ru.`;
    case "home":
      return `${HI} Пишу с главной ${ON}.`;
    case "page":
    case "service":
    case "niche":
      // тот же текст, что был на услугах и нишах: "Пишу со страницы "X" на lstmind.ru."
      return `${HI} Пишу со страницы "${from.name}" ${ON}.`;
    case "case":
      return `${HI} Смотрю разбор "${from.name}" ${ON}, хочу обсудить похожий сайт.`;
    case "works":
      return `${HI} Смотрю ваши работы ${ON}, ближе всего вот этот проект: `;
    case "audit":
      return (from.diag ? AUDIT_DIAG : AUDIT).tg;
  }
}

/** ссылка в Telegram сразу с первым сообщением */
export const tgLink = (from: TgFrom) => tgHref(tgText(from));

