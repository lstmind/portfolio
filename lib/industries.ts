export const industryBySlug = (slug: string) => INDUSTRY_PAGES.find((i) => i.slug === slug);

/** название и движок работы берём из общего списка, чтобы данные не разъезжались */
export function workByHref(href: string) {
  const featured = WORKS.find((w) => w.href === href);
  if (featured) return { title: featured.title, engine: featured.stack.join(" · ") };
  const item = WORKS_INDEX.find((w) => w.href === href);
  return item ? { title: item.title, engine: item.engine } : null;
}
