/**
 * Число из строки цены («от 15 000 ₽» → 15000, «аудит бесплатно» → 0).
 * Разметке нужна цифра: строкой поисковик цену не покажет, а Offer без цены
 * для него просто пустой.
 */
export function priceNumber(value: string): number | null {
  if (/бесплатн/i.test(value)) return 0;
  const m = value.replace(/ |\s/g, "").match(/\d+/);
  return m ? Number(m[0]) : null;
}

/** 2000 → "2 000": разряды обычным пробелом, для title и description */
const digits = (n: number) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ");

