/**
 * Один скрин отдаётся четырьмя размерами: 400 для телефона, 760 для ленты на главной,
 * 1128 для страницы кейса, 1692 (снятый в 1.5x) для ретины. Иначе браузер тянет
 * узкий файл и растягивает его — от этого и была грязь в тенях.
 */
export const shotSrcSet = (jpg: string) => {
  const b = jpg.replace(/\.jpg$/, "");
  return `${b}-400.webp 400w, ${b}-760.webp 760w, ${b}-1128.webp 1128w, ${b}.webp 1692w`;
};

