/** склонение существительного при числе: 1 проект, 2 проекта, 5 проектов */
export function plural(n: number, forms: [string, string, string]) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return forms[2];
  if (b > 1 && b < 5) return forms[1];
  if (b === 1) return forms[0];
  return forms[2];
}

/** адрес сайта без схемы, www и слэша на конце: по нему сверяем дубли */
export const hostOf = (href: string) => href.replace(/^https?:\/\/(www\.)?/, "").replace(/\/+$/, "");

