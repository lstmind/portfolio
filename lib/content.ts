export const TITLE_TAIL = " | lstmind";

/**
 * Цифры в title, description и подписях страниц берутся из её же данных, а не пишутся второй раз руками:
 * {price} цена ("от 30 000 ₽"), {term} срок ("3–5 дней"), {rate} ставка ("от 2 000 ₽/час").
 * Поменяли цену в price.value, поменялись и сниппет, и разметка.
 */
export function fillMeta(text: string, d: { price: { value: string }; term: { value: string } }) {
  return text
    .replace(/\{price\}/g, d.price.value)
    .replace(/\{term\}/g, d.term.value)
    .replace(/\{rate\}/g, `от ${digits(SITE.ratePerHour)} ₽/час`)
    // "форма заявки. от 30 000 ₽": предложение, которое началось с подстановки, с заглавной
    .replace(/(^|[.!?]\s+)([а-яёa-z])/g, (_, a: string, b: string) => a + b.toUpperCase());
}

