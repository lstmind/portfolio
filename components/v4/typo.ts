/**
 * Склейка для строк из lib, которые идут в вёрстку как есть ("сайт с онлайн-записью: от 25 000 ₽", "2–3 недели"):
 * число не рвётся по разрядам, "₽" и "от" не отрываются от числа, диапазон "2–3" не переносится после тире.
 */
const NB = " ";
const WJ = "⁠";

export const tie = (s: string) =>
  s
    .replace(/(\d) (?=\d{3}(?!\d))/g, `$1${NB}`)
    .replace(/(\d) (₽|%)/g, `$1${NB}$2`)
    .replace(/(^|[\s(])(от|до) (?=\d)/gi, `$1$2${NB}`)
    .replace(/(\d)–(?=\d)/g, `$1–${WJ}`);
