/**
 * Склейка для строк из lib, которые идут в вёрстку как есть ("сайт с онлайн-записью: от 25 000 ₽", "2–3 недели"):
 * число не рвётся по разрядам, "₽" и "от" не отрываются от числа, диапазон "2–3" не переносится после тире,
 * короткие предлоги и союзы ("в", "с", "и", "на", "не"...) не висят в конце строки.
 */
const NB = " ";
const WJ = "⁠";

export const tie = (s: string) =>
  s
    .replace(/(\d) (?=\d{3}(?!\d))/g, `$1${NB}`)
    .replace(/(\d) (₽|%)/g, `$1${NB}$2`)
    // число с единицей: "8 часов", "3 дня", "50–100 тыс. ₽" не разъезжаются по строкам
    .replace(/(\d) (?=(?:дн[а-яё]*|день|недел[а-яё]*|месяц[а-яё]*|час|часа|часов|часам|мин|минут[а-яё]*|секунд[а-яё]*|лет|год|года|году|страниц[а-яё]*|экран[а-яё]*|позици[а-яё]*|шаг[а-яё]*|тыс\.|млн)(?![a-zа-яё]))/gi, `$1${NB}`)
    .replace(/(^|[\s(])(от|до) (?=\d)/gi, `$1$2${NB}`)
    // "с 10 до 22", "от 2 до 3": число не отрывается от следующего "до"
    .replace(/(\d) (?=до\s\d)/g, `$1${NB}`)
    .replace(/(?<=^|[\s(«„"])(в|во|с|со|к|ко|у|о|об|и|а|но|на|не|ни|по|за|из|от|до) /gi, `$1${NB}`)
    .replace(/(\d)–(?=\d)/g, `$1–${WJ}`)
    .replace(/тыс\. ₽/g, `тыс.${NB}₽`)
    // "₽/час", "₽/мес" не рвутся на косой черте
    .replace(/₽\/(?=час|мес)/g, `₽/${WJ}`)
    // "1С-программист": огрызок из двух знаков с дефисом не остаётся в конце строки
    .replace(/(?<=(?:^|[\s(«„"])[0-9A-Za-zА-Яа-яЁё]{1,2})-(?=[А-Яа-яЁё])/g, `-${WJ}`);
